const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  meta: () => ipcRenderer.invoke('meta'),
  pickImages: () => ipcRenderer.invoke('pick-images'),
  pickFont: () => ipcRenderer.invoke('pick-font'),
  readImage: (p) => ipcRenderer.invoke('read-image', p),
  openProjectDialog: () => ipcRenderer.invoke('open-project-dialog'),
  openProjectPath: (dir) => ipcRenderer.invoke('open-project-path', dir),
  recentList: () => ipcRenderer.invoke('recent-list'),
  recentClear: () => ipcRenderer.invoke('recent-clear'),
  saveProject: (payload) => ipcRenderer.invoke('save-project', payload),
  generateCode: (payload) => ipcRenderer.invoke('generate-code', payload),
  exportZeus: (payload) => ipcRenderer.invoke('export-zeus', payload),
  buildZeus: (payload) => ipcRenderer.invoke('build-zeus', payload),  qr: (opts) => ipcRenderer.invoke('qr', opts),
  installStatus: () => ipcRenderer.invoke('install-status'),
  installStart: (payload) => ipcRenderer.invoke('install-start', payload),
  installBuild: (payload) => ipcRenderer.invoke('install-build', payload),
  installStop: () => ipcRenderer.invoke('install-stop'),
  installOpenFolder: () => ipcRenderer.invoke('install-open-folder'),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  onBuildLog: (cb) => ipcRenderer.on('build-log', (_e, line) => cb(line)),
  onLanRequest: (cb) => ipcRenderer.on('lan-request', (_e, req) => cb(req)),
});
